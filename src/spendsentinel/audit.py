"""Run the SQL audit tests, export tables for Tableau and write the findings report."""

from __future__ import annotations

from pathlib import Path

import duckdb
import pandas as pd

from .config import DB_PATH, EXPORTS_DIR, REPORTS_DIR, SQL_DIR

# Order matters: a payment caught by several pairs is reported once, at its highest tier.
TIER_RANK = "CASE confidence WHEN 'high' THEN 5 WHEN 'medium' THEN 4 WHEN 'low' THEN 3 " \
            "WHEN 'no_reference' THEN 2 ELSE 1 END"
RANK_TIER = "CASE level WHEN 5 THEN 'high' WHEN 4 THEN 'medium' WHEN 3 THEN 'low' " \
            "WHEN 2 THEN 'no_reference' ELSE 'bulk' END"
DUPLICATE_TIERS = ("high", "medium", "low")

EXPORTS = {
    "payments": f"""
        SELECT p.*,
               d.confidence AS duplicate_tier,
               coalesce(d.confidence IN {DUPLICATE_TIERS}, false) AS possible_duplicate,
               abs(p.amount_pence) < 2500000 AS below_publication_threshold
        FROM payments p
        LEFT JOIN (
            SELECT second_payment_id, {RANK_TIER.replace('level', f'max({TIER_RANK})')} AS confidence
            FROM audit_possible_duplicates GROUP BY second_payment_id
        ) d ON d.second_payment_id = p.payment_id
    """,
    "possible_duplicates": f"SELECT * FROM audit_possible_duplicates ORDER BY {TIER_RANK} DESC, amount_gbp DESC",
    "supplier_spend": "SELECT * FROM supplier_ranked ORDER BY dept_code, rank",
    "supplier_concentration": "SELECT * FROM audit_supplier_concentration",
    "monthly_trend": "SELECT * FROM monthly_trend",
    "cross_department_suppliers": "SELECT * FROM audit_cross_department_suppliers",
}


def money(value: float) -> str:
    sign = "-" if value < 0 else ""
    value = abs(value)
    if value >= 1e9:
        return f"{sign}£{value / 1e9:,.2f}bn"
    if value >= 1e6:
        return f"{sign}£{value / 1e6:,.1f}M"
    if value >= 1e3:
        return f"{sign}£{value / 1e3:,.1f}k"
    return f"{sign}£{value:,.2f}"


def duplicate_summary(con: duckdb.DuckDBPyConnection) -> pd.DataFrame:
    """One row per tier. Each later payment is counted once, at its highest tier."""
    return con.execute(f"""
        WITH best AS (
            SELECT second_payment_id, max(amount_gbp) AS amount_gbp, max({TIER_RANK}) AS level
            FROM audit_possible_duplicates GROUP BY second_payment_id
        )
        SELECT {RANK_TIER} AS tier, count(*) AS payments, sum(amount_gbp) AS amount_gbp
        FROM best GROUP BY level ORDER BY level DESC
    """).df()


def _write_findings(con: duckdb.DuckDBPyConnection) -> Path:
    scope = con.execute("""
        SELECT count(*) AS payments, sum(amount_gbp) AS spend,
               count(DISTINCT dept_code) AS departments,
               min(period_month) AS first_month, max(period_month) AS last_month
        FROM payments
    """).df().iloc[0]
    tiers = duplicate_summary(con).set_index("tier")
    flagged = tiers.loc[[t for t in DUPLICATE_TIERS if t in tiers.index]]
    top_pairs = con.execute("""
        SELECT dept_code, supplier_name, amount_gbp, first_date, first_expense_type
        FROM audit_possible_duplicates WHERE confidence = 'high'
        ORDER BY amount_gbp DESC LIMIT 10
    """).df()
    concentration = con.execute("SELECT * FROM audit_supplier_concentration").df()
    cross = con.execute("""
        SELECT count(*) AS suppliers, sum(spend_gbp) AS spend_gbp FROM audit_cross_department_suppliers
    """).df().iloc[0]
    top_cross = con.execute("""
        SELECT supplier_name, department_list, spend_gbp FROM audit_cross_department_suppliers LIMIT 5
    """).df()

    def tier_row(name: str, label: str) -> str:
        if name not in tiers.index:
            return f"| {label} | 0 | £0 |"
        r = tiers.loc[name]
        return f"| {label} | {int(r.payments):,} | {money(r.amount_gbp)} |"

    out = ["# Audit findings", "",
           f"Scope: {int(scope.payments):,} payments worth {money(scope.spend)} from "
           f"{int(scope.departments)} departments, {scope.first_month:%B %Y} to {scope.last_month:%B %Y}. "
           "Generated by `spendsentinel audit`.", "",
           "Every finding below is a lead for review, not proof of an error.", "",
           "## Possible duplicate payments", "",
           f"**{int(flagged.payments.sum()):,} payments worth {money(flagged.amount_gbp.sum())}** match an "
           "earlier payment from the same department to the same supplier, for the same amount to the penny, "
           "within 7 days, under a different payment reference. Each later payment is counted once.", "",
           "| Tier | Payments | Amount |", "| --- | ---: | ---: |",
           tier_row("high", "High: same day, same expense type and description"),
           tier_row("medium", "Medium: within 7 days, same expense type"),
           tier_row("low", "Low: within 7 days, different expense type"),
           "", "Set aside, not counted above:", "",
           "| Group | Payments | Amount |", "| --- | ---: | ---: |",
           tier_row("bulk", "Bulk orders: 4+ identical payments within 7 days (for example a vehicle fleet)"),
           tier_row("no_reference", "No reference: one payment has no transaction number"),
           ]
    if not top_pairs.empty:
        out += ["", "Largest high-tier pairs:", "",
                "| Dept | Supplier | Amount | Paid twice on | Expense type |",
                "| --- | --- | ---: | --- | --- |"]
        for r in top_pairs.itertuples():
            expense = (r.first_expense_type or "")
            expense = expense if len(expense) <= 60 else expense[:57].rstrip() + "..."
            out.append(f"| {r.dept_code} | {r.supplier_name} | {money(r.amount_gbp)} | "
                       f"{r.first_date:%d %b %Y} | {expense} |")
    out += ["", "## Supplier concentration", "",
            "| Dept | Suppliers | Spend | Top 10 share | Suppliers for 80% | HHI | Largest supplier |",
            "| --- | ---: | ---: | ---: | ---: | ---: | --- |"]
    for r in concentration.itertuples():
        out.append(f"| {r.dept_code} | {r.suppliers:,} | {money(r.spend_gbp)} | {r.top10_share:.0%} | "
                   f"{r.suppliers_for_80:,} | {r.hhi:,.0f} | {r.largest_supplier} ({r.largest_supplier_share:.0%}) |")
    out += ["", "HHI runs from 0 to 10,000; above 2,500 means spend sits with a few suppliers.", "",
            "## Suppliers paid by more than one department", "",
            f"{int(cross.suppliers):,} suppliers, {money(cross.spend_gbp or 0)} in total. Largest:", "",
            "| Supplier | Departments | Spend |", "| --- | --- | ---: |"]
    for r in top_cross.itertuples():
        out.append(f"| {r.supplier_name} | {r.department_list} | {money(r.spend_gbp)} |")
    out.append("")

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    path = REPORTS_DIR / "audit_findings.md"
    path.write_text("\n".join(out), encoding="utf-8")
    return path


def run() -> None:
    EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    with duckdb.connect(str(DB_PATH)) as con:
        for sql_file in sorted((SQL_DIR / "audit").glob("*.sql")):
            con.execute(sql_file.read_text(encoding="utf-8"))
        for name, query in EXPORTS.items():
            con.execute(query).df().to_csv(EXPORTS_DIR / f"{name}.csv", index=False)
        report = _write_findings(con)
        tiers = duplicate_summary(con)
    for r in tiers.itertuples():
        print(f"{r.tier:>12}: {r.payments:,} payments, {money(r.amount_gbp)}")
    print(f"exports: {len(EXPORTS)} CSVs in exports/   report: {report.relative_to(REPORTS_DIR.parent)}")
